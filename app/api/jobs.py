from uuid import UUID
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.session import get_session
from app.models.job import Job, JobStatus
from app.schemas.job import JobCreate, JobResponse
from app.models.outbox import OutboxEvent
from app.services.job_service import JobService

router = APIRouter()

@router.post(
    "",
    response_model = JobResponse,
    status_code = status.HTTP_201_CREATED,
)
async def create_job(
    job_data: JobCreate,
    session: AsyncSession = Depends(get_session),
) -> Job:
    job = Job(
        job_type=job_data.job_type,
        payload=job_data.payload,
        status=JobStatus.PENDING,
        priority = job_data.priority,
        max_attempts = job_data.max_attempts,
    )
    session.add(job)
    await session.flush()  #flushes the changes to the database but does not commit the transaction. This is important because we need the job.id to create the outbox event, and job.id is generated by the database upon insertion. By flushing, we ensure that job.id is populated before we create the outbox event.
    outbox_event = OutboxEvent(
        job_id=job.id,
        event_type="JOB_CREATED",
        payload={
            "job_id": str(job.id),
            "job_type": job.job_type,
            "payload": job.payload,
            "priority": job.priority.value,
        },
    )
    session.add(outbox_event)            #puts the object into SQLAlchemy's session, but does not yet write it to the database
    await session.commit()      #writes the changes to the database and commits the transaction. If there are any issues (like constraint violations), this is where an exception would be raised.
    await session.refresh(job)  #refreshes the job object with the latest data from the database. This is especially useful for fields that are automatically generated by the database (like the id or timestamps). After this call, job will have its id populated.
    return job


@router.get(
    "/{job_id}",
    response_model=JobResponse,
)
async def get_job(
    job_id: UUID,
    session: AsyncSession = Depends(get_session),
) -> Job:
    service = JobService(session)

    job = await service.get_job(job_id)

    if job is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Job not found",
        )

    return job

@router.get(
    "",
    response_model = list[JobResponse],
)
async def list_jobs(
    session: AsyncSession = Depends(get_session),
) -> list[Job]:
    service = JobService(session)
    return await service.list_jobs()

